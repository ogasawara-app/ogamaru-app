const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html','utf8');
const app = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x=>x[1]).sort((a,b)=>b.length-a.length)[0];
const prefix = app.split('// 5. Event Listeners & Init')[0];
const context = vm.createContext({console, document: {addEventListener() {}}});
vm.runInContext(prefix + `
  globalThis.run = (source) => eval(source);
`, context);
const run = context.run;
assert.equal(run('ogaConfirmed()'), false);
run(`state.liveData = {schema_version:2, updated_iso:new Date().toISOString(), source_status:{ogamaru_next:'ok',ogamaru_info:'ok',ogamaru_blog_feed:'ogamaru_blog_feed: ok (5 items)',hahajima_status:'ok'},alerts:[],persisted_overrides:[]};state.syncOK=true;`);
assert.equal(run('ogaConfirmed()'), true);
run('state.liveData.source_status.ogamaru_blog_feed="error"');
assert.equal(run('ogaConfirmed()'), false);
run('state.liveData.updated_iso=new Date(Date.now()-66*60000).toISOString()');
assert.equal(run('dataFresh()'), false);
run('state.liveData.updated_iso=new Date().toISOString(); state.syncOK=false');
assert.equal(run('dataFresh()'), false);
run(`state.liveData.persisted_overrides=[{target_date:'2026-12-01',type:'dep',new_time:'13:00'}]`);
assert.equal(run(`getDayInfo('2026-12-01').ogamaru.time`),'13:00');
run(`state.liveData.persisted_overrides[0].new_time='15:00'`);
assert.equal(run(`getDayInfo('2026-12-01').ogamaru.isChanged`),false);
run(`state.liveData.cancellations=[{target_date:'2026-12-01',type:'dep'}]`);
assert.equal(run(`getDayInfo('2026-12-01').ogamaru.cancelled`),true);
assert.equal(run(`getDayInfo('2027-05-10').haha.status`),'unknown');
assert.equal(run(`escapeHtml('<img>')`),'&lt;img&gt;');
run(`state.syncOK=true;state.liveData.notice_schema=1;state.liveData.source_status.ogamaru_blog_feed='ogamaru_blog_feed: ok (5 items)';state.liveData.alerts=[{target_dates:['9999-12-01']}];state.liveData.unresolved_notices=[{title:'old undated notice'}];state.liveData.cancellations=[];`);
assert.equal(run(`ogaNeedsCheck('9999-12-01')`),true);
assert.equal(run(`ogaNeedsCheck('9999-12-02')`),false);
assert.equal(run(`ogaNeedsCheck()`),true);
run(`state.liveData.alerts=[{target_dates:['2000-01-01']}];`);
assert.equal(run('currentNotices().length'),0);
assert.equal(run('unresolvedNotices().length'),1);
run(`state.liveData.unresolved_notices=[];`);
assert.equal(run('ogaNeedsCheck()'),false);
console.log('16 frontend assertions passed');
